class fastdownPlanner(base.BaseModule):
    '''
    fastdown FF planner
    '''
    

    def __init__(self,
                 ff_goals_from_midca_goals,
                 ff_state_from_midca_state,
                 domain_file,
                 state_file,world_planner= None):

        self.ff_goals_from_midca_goals = ff_goals_from_midca_goals
        self.ff_state_from_midca_state = ff_state_from_midca_state
        self.domain_file = domain_file
        self.state_file = state_file
        self.world_planner = world_planner
        

        try:
            self.working = True
        except:
            print("Error declaring ff  operators. This planner will be \
                       disabled")
            traceback.print_exc()
            self.working = False

    def init(self, world, mem):
        self.world = world
        self.mem = mem
        self.mem.set(self.mem.PLANNING_COUNT, 0)

    # this will require a lot more error handling, but ignoring now for debugging.
    def run(self, cycle, verbose=2):

        current_state = self.mem.get(self.mem.STATES)[-1]
        world1 = copy.deepcopy(self.world_planner)
        for atom in world1.atoms:
            self.world_planner.remove_atom(atom)

        for atom in current_state.atoms:
            self.world_planner.add_atom(atom)
        world = self.world_planner
        try:
            goals = self.mem.get(self.mem.CURRENT_GOALS)[-1]
        except:
            goals = []

        trace = self.mem.trace
        if trace:
            trace.add_module(cycle, self.__class__.__name__)
            trace.add_data("WORLD", copy.deepcopy(world))
            trace.add_data("GOALS", copy.deepcopy(goals))

        if not goals:
            if verbose >= 2:
                print("No goals received by planner. Skipping planning.")
            return
        try:
            midcaPlan = self.mem.get(self.mem.GOAL_GRAPH).getMatchingPlan(goals)

        except AttributeError:
            midcaPlan = None

        if midcaPlan:
            if verbose >= 2:
                print("Old plan retrieved. Checking validity...",)
            valid = world.plan_correct(midcaPlan)
            if not valid:
                midcaPlan = None
                # if plan modification is added to MIDCA, do it here.
                if verbose >= 2:
                    print()
                    "invalid."
            elif verbose >= 2:
                print()
                "valid."
            if valid:
                if verbose >= 2:
                    print(
                    "checking to see if all goals are achieved...",)
                achieved = world.plan_goals_achieved(midcaPlan)

                #for goal in midcaPlan.goals:
                #    if(self.world.atom_true(self.world.midcaGoalAsAtom(goal)) == True):
                #        achieved.add(goal)
                if verbose >= 2:
                    if len(achieved) == len(midcaPlan.goals):
                        print("yes")
                    else:
                        print("no. Goals achieved: " + str({str(goal) for goal in achieved}))
                if len(achieved) != len(midcaPlan.goals):
                    midcaPlan = None  # triggers replanning.
        
        # ensure goals is a collection to simplify things later.
        if not isinstance(goals, collections.Iterable):
            goals = [goals]

        if not midcaPlan:
            # use pyhop to generate new plan
            if verbose >= 2:
                print("Planning...")
            try:
                self.ff_state_from_midca_state(self.world, self.state_file)
                ffgoals = self.ff_goals_from_midca_goals(goals, self.state_file)
                

            except Exception as e:
                print(str(e))
            try:

                
                self.mem.set(self.mem.PLANNING_COUNT, 1 + self.mem.get(self.mem.PLANNING_COUNT))
                #running fast downward planner with the given domain and state file
                try:
                    fast_downward.plan(self.domain_file, self.state_file, "--search", "lazy_greedy([ff])")
                except:
                    pass

                #formatting from planning generated by fastdownward to midcaplan as required.
                f = open("sas_plan","r")
                ffplan = f.read().split()

                for i in range(len(ffplan)):
                    ffplan[i] = ffplan[i].replace("(","")
                    ffplan[i] = ffplan[i].replace(")","")
                ffplan = ffplan[:-6]

                ffPlan1=[]
                for i in range(len(ffplan)):
                    if(ffplan[i] == "move"):

                        ffPlan1.append(tuple([ffplan[i],ffplan[i+1],ffplan[i+2],ffplan[i+3]]))
                        i=i+4
                    elif(ffplan[i] == "spray"):
                        o = ['spray']

                        for k in range(i + 1, len(ffplan)):
                            if ffplan[k] not in ['spray', 'move','inform']:
                                #print(a[k])
                                o.append(ffplan[k])
                            else:
                                break
                        ffPlan1.append(tuple(o))
                        i = i + len(o)
                    elif(ffplan[i] == "inform"):
                        self.mem.REBEL_EVALUATION += 1
                        ffPlan1.append(tuple([ffplan[i],ffplan[i+1],ffplan[i+2],ffplan[i+3],ffplan[i+4]]))
                        i=i+5
                    else:
                        pass
                ffPlan= ffPlan1
                print(ffPlan)
            except Exception as e:
                ffPlan = None
            if  not ffPlan and ffPlan != []:
                if verbose >= 1:
                    print("Planning failed for ",)
                    for goal in goals:
                        print(goal, " ",)
                    print()
                if trace: trace.add_data("PLAN", ffPlan)
                return
            # change from ff plan to MIDCA plan
            midcaPlan = plans.Plan([plans.Action(action[0], *list(action[1:])) for action in ffPlan], goals)
            if verbose >= 1:
                print("Planning complete.")
            if verbose >= 2:
                print("Plan: " ) # , midcaPlan
                for a in midcaPlan:
                    print(("" + str(a)))
            # save new plan
            if ffPlan != None:
                
                self.mem.get(self.mem.GOAL_GRAPH).addPlan(midcaPlan)
                self.mem.PLAN = midcaPlan
                #print(self.mem.get(self.mem.GOAL_GRAPH))
            if trace: trace.add_data("PLAN", midcaPlan)
